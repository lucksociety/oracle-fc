"""Derive the dashboard palette from the Luck Society X brand assets.

Assets were downloaded from the public X profile @lucksociety
(profile image + banner) into web/assets/. This script quantises each image
(median-cut, 8 colours) and writes web/assets/palette.json, which the CSS
variables in web/style.css are based on.
"""
import json
from pathlib import Path

from PIL import Image

ASSETS = Path(__file__).resolve().parent.parent / "web" / "assets"


def dominant(path: Path, k: int = 8):
    im = Image.open(path).convert("RGB").resize((150, 150))
    q = im.quantize(colors=k, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()[: k * 3]
    out = []
    for count, idx in sorted(q.getcolors(), reverse=True):
        r, g, b = pal[idx * 3: idx * 3 + 3]
        out.append({"hex": f"#{r:02x}{g:02x}{b:02x}", "share": round(count / (150 * 150), 4)})
    return out


if __name__ == "__main__":
    pal = {"logo": dominant(ASSETS / "logo.jpg"), "banner": dominant(ASSETS / "banner.jpg")}
    (ASSETS / "palette.json").write_text(json.dumps(pal, indent=2))
    print(json.dumps(pal, indent=2))
    Image.open(ASSETS / "logo.jpg").convert("RGB").resize((64, 64)).save(ASSETS / "favicon.png")


# ---------------------------------------------------------------- theme roles
import colorsys  # noqa: E402


def _hls(h):
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return colorsys.rgb_to_hls(r, g, b)


def _mix(h, t, other="#ffffff"):
    a = [int(h[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(other[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(a, b))


def theme(pal: dict) -> dict:
    """Assign UI roles (colorsys HLS: index 0 hue, 1 lightness, 2 saturation) to extracted colours by hue / lightness / saturation rules."""
    logo, banner = [c["hex"] for c in pal["logo"]], [c["hex"] for c in pal["banner"]]
    allc = logo + banner
    golds = [c for c in logo if 35 / 360 <= _hls(c)[0] <= 60 / 360 and _hls(c)[1] > 0.3 and _hls(c)[2] > 0.6]
    greens = [c for c in logo if 90 / 360 <= _hls(c)[0] <= 160 / 360 and _hls(c)[2] > 0.5 and _hls(c)[1] > 0.12]
    darks = sorted(banner, key=lambda c: _hls(c)[1])
    teal = max((c for c in banner if 160 / 360 <= _hls(c)[0] <= 200 / 360), key=lambda c: _hls(c)[1], default=darks[1])
    bronze = max((c for c in banner if 30 / 360 <= _hls(c)[0] <= 50 / 360), key=lambda c: _hls(c)[1])
    gold = max(golds, key=lambda c: next(x["share"] for x in pal["logo"] if x["hex"] == c))
    gold_bright = max(golds, key=lambda c: _hls(c)[1])
    green = max(greens, key=lambda c: next(x["share"] for x in pal["logo"] if x["hex"] == c))
    bg = darks[0]
    return {"bg": bg, "surface": teal, "surface-2": _mix(teal, 0.06), "border": _mix(bronze, 0.55, bg), "gold": gold, "gold-bright": gold_bright, "bronze": bronze,
            "green": green, "green-bright": _mix(green, 0.35), "text": _mix(gold_bright, 0.85),
            "muted": _mix(bronze, 0.35), "danger": "#d9534f", "_sources": allc}


def write_theme(pal: dict, path: Path):
    t = theme(pal)
    lines = ["/* AUTO-GENERATED by scripts/extract_palette.py from the @lucksociety logo + banner. */", ":root {"]
    lines += [f"  --{k}: {v};" for k, v in t.items() if not k.startswith("_")]
    lines.append("}")
    path.write_text("\n".join(lines) + "\n")
    return t


if __name__ == "__main__":
    pal = json.loads((ASSETS / "palette.json").read_text())
    print(write_theme(pal, ASSETS / "theme.css"))
